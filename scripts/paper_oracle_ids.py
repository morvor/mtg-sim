#!/usr/bin/env python3
"""Write data/paper_oracle_ids.txt: the Oracle ids of the cards with at least one paper
printing, from Scryfall's "Default Cards" bulk data (every printing). A printing is a paper
printing when its `games` contains "paper".

data/oracle_cards.jsonl.gz has one printing per Oracle id, and that printing can be an MTGO-
or Arena-only reprint of a paper card (Masters Edition, Vintage Masters, Tempest Remastered,
MTGO duel decks, Arena starter decks), so paper status comes from every printing:
`ScryfallCard::is_paper_card` (crates/mtg-data) and `is_paper` (scripts/rulings_batches.py)
read this file. The script also records the file and its source in data/manifest.json.

Regenerate it whenever data/oracle_cards.jsonl.gz is updated: the mtg-data test
`the_paper_list_covers_the_card_data` fails when the list is older than the card data.

Usage (from the repo root):
  python3 scripts/paper_oracle_ids.py                  # download the current default_cards
  python3 scripts/paper_oracle_ids.py --input FILE [--updated-at TIME]
      # a default_cards or all_cards bulk file already downloaded (.json, .jsonl, or either
      # gzipped), and its Scryfall `updated_at`
"""
import argparse
import datetime
import gzip
import hashlib
import json
import os
import shutil
import sys
import tempfile
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = 'data/paper_oracle_ids.txt'
MANIFEST = 'data/manifest.json'
BULK_DATA = 'https://api.scryfall.com/bulk-data/default-cards'
# Scryfall asks API clients to send both.
HEADERS = {'User-Agent': 'mtg-sim/0.1 (scripts/paper_oracle_ids.py)', 'Accept': 'application/json'}
HEADER = """\
# Oracle ids of the cards with at least one paper printing (Scryfall `games` contains "paper"),
# from Scryfall's default_cards bulk data; source and date in data/manifest.json.
# Generated by scripts/paper_oracle_ids.py; do not edit by hand.
"""


def now():
    t = datetime.datetime.now(datetime.timezone.utc)
    return t.isoformat(timespec='milliseconds').replace('+00:00', 'Z')


def download(dest):
    """Downloads the current default_cards file to `dest`; returns its bulk-data object."""
    with urllib.request.urlopen(urllib.request.Request(BULK_DATA, headers=HEADERS)) as r:
        meta = json.load(r)
    req = urllib.request.Request(meta['download_uri'], headers={**HEADERS, 'Accept': '*/*'})
    with urllib.request.urlopen(req) as r, open(dest, 'wb') as f:
        shutil.copyfileobj(r, f, 1 << 20)
    return meta


def paper_oracle_ids(path):
    """(Oracle ids with a paper printing, number of printings read) from a bulk file: a
    JSON array with one card per line, as Scryfall writes it, or one card per line."""
    ids = set()
    printings = 0
    opener = gzip.open if path.endswith('.gz') else open
    with opener(path, 'rt', encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.strip().rstrip(',')
            if line in ('', '[', ']'):
                continue
            try:
                c = json.loads(line)
            except json.JSONDecodeError as e:
                sys.exit(f'{path}:{n}: expected one card per line ({e})')
            printings += 1
            if 'paper' not in (c.get('games') or []):
                continue
            # A reversible card's printing has an Oracle id on each face instead.
            for oid in [c.get('oracle_id')] + [f.get('oracle_id') for f in c.get('card_faces') or []]:
                if oid:
                    ids.add(oid)
    return ids, printings


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--input', help='a downloaded default_cards or all_cards bulk file')
    ap.add_argument('--updated-at', help="the input's Scryfall updated_at (with --input)")
    args = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        if args.input:
            path = args.input
            meta = {'type': 'default_cards or all_cards', 'updated_at': args.updated_at}
            fetched_at = datetime.datetime.fromtimestamp(
                os.path.getmtime(path), datetime.timezone.utc).isoformat(
                timespec='milliseconds').replace('+00:00', 'Z')
        else:
            path = os.path.join(tmp, 'default-cards.json')
            fetched_at = now()
            meta = download(path)
        ids, printings = paper_oracle_ids(path)
        source = {
            'bulk_data': meta.get('type'),
            'download_uri': meta.get('download_uri'),
            'size': os.path.getsize(path),
            'sha256': sha256(path),
            'printings': printings,
        }
    out = os.path.join(ROOT, OUT)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER)
        f.writelines(oid + '\n' for oid in sorted(ids))
    manifest_path = os.path.join(ROOT, MANIFEST)
    with open(manifest_path, encoding='utf-8') as f:
        manifest = json.load(f)
    manifest['paper_oracle_ids'] = {
        'updated_at': meta.get('updated_at'),
        'size': os.path.getsize(out),
        'sha256': sha256(out),
        'file': OUT,
        'fetched_at': fetched_at,
        'oracle_ids': len(ids),
        'source': source,
        'generated_by': 'scripts/paper_oracle_ids.py',
    }
    with open(manifest_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(json.dumps(manifest, indent=2))
    print(f'{len(ids)} Oracle ids with a paper printing, from {printings} printings: wrote {OUT} '
          f'and {MANIFEST}')


if __name__ == '__main__':
    main()
