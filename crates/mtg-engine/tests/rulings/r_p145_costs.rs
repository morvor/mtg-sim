fn castable(t: &mut TestGame, card: ObjectId) -> bool {
    !legal_cast_methods(t, P0, card).is_empty()
}

#[test]
fn baral_reduces_only_generic_mana_and_not_mana_value() {
    cr!("601.2f", "118.7", "202.3");
    ruling!(
        "Baral, Chief of Compliance",
        "The cost reduction applies only to generic mana in the cost of instant and sorcery spells you cast."
    );
    ruling!(
        "Baral, Chief of Compliance",
        "To determine the total cost of a spell, start with the mana cost or alternative cost you're paying (such as a flashback cost), add any cost increases (such as kicker costs), then apply any cost reductions"
    );
    supported("Baral, Chief of Compliance");
    // Dark Ritual ({B}) still needs {B}; Divination ({2}{U}) costs {1}{U}.
    let mut t = TestGame::new(2);
    t.battlefield(P0, "Baral, Chief of Compliance");
    t.lands(P0, "Island", 1);
    let wastes = t.lands(P0, "Wastes", 1);
    let ritual = t.hand(P0, "Dark Ritual");
    let divination = t.hand(P0, "Divination");
    assert!(!castable(&mut t, ritual));
    assert!(castable(&mut t, divination));
    t.cast(P0, divination).go();
    assert!(t.obj_now(wastes[0]).tapped);
    assert_eq!(crate::r_s01_common::tapped_lands(&t, P0), 2);
    // Think Twice's flashback cost ({2}{U}) costs {1}{U}; the spell's mana value is still
    // that of its mana cost ({1}{U}: 2).
    let mut t = TestGame::new(2);
    t.battlefield(P0, "Baral, Chief of Compliance");
    t.lands(P0, "Island", 2);
    let twice = t.graveyard(P0, "Think Twice");
    let spell = t
        .cast(P0, twice)
        .method(CastMethod::Keyword(KeywordKind::Flashback))
        .go();
    assert_eq!(crate::r_s01_common::tapped_lands(&t, P0), 2);
    assert_eq!(t.g.mana_value_of(spell), 2);
}

#[test]
fn pollywog_symbiote_reduces_generic_for_any_mutate_creature_spell() {
    cr!("601.2f", "118.7", "702.140a");
    ruling!(
        "Pollywog Symbiote",
        "Effects that reduce the generic mana cost of a spell (such as that of Pollywog Symbiote) can’t reduce that spell’s colored mana requirements."
    );
    ruling!(
        "Pollywog Symbiote",
        "Pollywog Symbiote’s first ability applies to creature spells you cast that have mutate even if you don’t cast them for their mutate cost."
    );
    supported("Pollywog Symbiote");
    // Gemrazer ({3}{G}, mutate {1}{G}{G}) cast normally costs {2}{G}: three Wastes can't
    // pay it, a Forest and two Wastes can.
    let mut t = TestGame::new(2);
    t.battlefield(P0, "Pollywog Symbiote");
    t.lands(P0, "Wastes", 3);
    let gemrazer = t.hand(P0, "Gemrazer");
    assert!(!castable(&mut t, gemrazer));
    let mut t = TestGame::new(2);
    t.battlefield(P0, "Pollywog Symbiote");
    t.lands(P0, "Wastes", 2);
    t.lands(P0, "Forest", 1);
    let gemrazer = t.hand(P0, "Gemrazer");
    t.cast(P0, gemrazer).go();
    t.settle();
    // ...and the loot trigger triggers for it.
    assert_eq!(triggers_on_stack(&t, "if it has mutate"), 1);
    // Its mutate cost {1}{G}{G} costs {G}{G}.
    let mut t = TestGame::new(2);
    t.battlefield(P0, "Pollywog Symbiote");
    let bears = t.battlefield(P0, "Grizzly Bears");
    t.lands(P0, "Forest", 2);
    let gemrazer = t.hand(P0, "Gemrazer");
    t.cast(P0, gemrazer)
        .method(CastMethod::Keyword(KeywordKind::Mutate))
        .target(obj(bears))
        .go();
    t.settle();
    assert_eq!(crate::r_s01_common::tapped_lands(&t, P0), 2);
    assert_eq!(triggers_on_stack(&t, "if it has mutate"), 1);
}

const TROYAN: &str = "Troyan, Gutsy Explorer";

/// P0's Troyan's mana ability ({G}{U}) is activated (the mana is in P0's pool).
fn troyan_mana(t: &mut TestGame) {
    supported(TROYAN);
    let troyan = t.battlefield(P0, TROYAN);
    let before = t.stack_len();
    t.activate(P0, troyan, 0, &[]).expect("mana ability");
    assert_eq!(t.stack_len(), before);
    assert_eq!(t.g.player(P0).mana_pool.total(), 2);
}

#[test]
fn troyan_mana_pays_any_part_of_an_x_spell_and_needs_no_single_spell() {
    cr!("106.6", "107.3");
    ruling!(
        "Troyan, Gutsy Explorer",
        "You can spend mana generated by Troyan on any part of the cost of a spell that contains {X} in its mana cost."
    );
    ruling!(
        "Troyan, Gutsy Explorer",
        "You don't have to spend the two mana on the same spell."
    );
    // Not on Grizzly Bears (mana value 2, no {X}).
    let mut t = TestGame::new(2);
    troyan_mana(&mut t);
    let bears = t.hand(P0, "Grizzly Bears");
    assert!(t.cast(P0, bears).try_go().is_err());
    // Two Fireballs with X=1, one after the other (the mana stays in the pool through the
    // step): each spends a Mountain's {R} and one of Troyan's mana for its {X}.
    let mut t = TestGame::new(2);
    troyan_mana(&mut t);
    t.lands(P0, "Mountain", 2);
    for i in 0..2 {
        let fireball = t.hand(P0, "Fireball");
        t.cast(P0, fireball).x(1).target(Entity::Player(P1)).go();
        assert_eq!(t.g.player(P0).mana_pool.total(), 1 - i);
        t.resolve_all();
    }
    assert_eq!(t.life(P1), 18);
}

#[test]
fn the_core_is_a_mana_ability() {
    cr!("605.1a", "605.3a", "605.3b");
    ruling!(
        "Matzalantli, the Great Door // The Core",
        "The Core's activated ability is a mana ability. It doesn't use the stack and can't be responded to."
    );
    let name = "Matzalantli, the Great Door // The Core";
    supported(name);
    let mut t = TestGame::new(2);
    let core = back_face(&mut t, P0, name);
    assert_eq!(name_of(&t, core), "The Core");
    t.graveyard(P0, "Grizzly Bears");
    t.graveyard(P0, "Forest");
    t.graveyard(P0, "Shock");
    t.activate(P0, core, 0, &[]).expect("mana ability");
    assert_eq!(t.stack_len(), 0);
    assert_eq!(t.g.player(P0).mana_pool.total(), 2);
}

#[test]
fn bards_company_needs_a_human_only_as_it_is_cast() {
    cr!("601.3", "702.8a", "601.2");
    ruling!(
        "Bard's Company",
        "If you use the first ability of Bard's Company to cast it as though it had flash, you must control a Human only as you begin the casting process"
    );
    supported("Bard's Company");
    // No Human: not at instant speed.
    let mut t = TestGame::new(2);
    t.set_step(P1, Step::End);
    t.g.turn.priority = Some(P0);
    let company = t.hand(P0, "Bard's Company");
    lands_for_cost(&mut t, P0, "Bard's Company");
    assert!(legal_cast_methods(&mut t, P0, company).is_empty());
    // A Human: cast in P1's end step; the Human dies in response; it still resolves.
    let vanguard = t.battlefield(P0, "Elite Vanguard");
    t.g.turn.priority = Some(P0);
    assert!(!legal_cast_methods(&mut t, P0, company).is_empty());
    let spell = t.cast(P0, company).go();
    destroy(&mut t, vanguard);
    t.resolve_all();
    assert!(t.on_battlefield(spell));
    assert_eq!(t.zone(spell), Zone::Battlefield);
}
