//! Rulings batch P143 — Nadu, Winged Wisdom's granted "becomes the target" trigger (CR
//! 603.2, 603.10, 113.7a) and Case File Auditor's "whenever you solve a Case".

use crate::r_p143_common::*;
use mtg_engine::object::Zone;
use mtg_engine::testing::*;
use mtg_engine::turn::Step;
use mtg_engine::*;

/// P0 casts Giant Growth on `target` (with a Forest for it); it stays on the stack.
fn grow(t: &mut TestGame, target: ObjectId) -> ObjectId {
    cast_new(t, P0, "Giant Growth", &[obj(target)])
}

/// The triggered abilities from Nadu's grant waiting on the stack.
fn nadu_triggers(t: &TestGame) -> usize {
    t.g.stack
        .iter()
        .filter(|s| {
            t.g.obj(**s).stack.as_ref().is_some_and(|i| {
                matches!(&i.kind, mtg_engine::object::StackKind::Triggered { ability, .. }
                    if ability.text.contains("twice"))
            })
        })
        .count()
}

#[test]
fn nadu_grants_the_ability_to_itself() {
    cr!("603.2", "611.3a");
    supported("Nadu, Winged Wisdom");
    ruling!(
        "Nadu, Winged Wisdom",
        "Nadu, Winged Wisdom's last ability grants a triggered ability to itself as well as other creatures you control."
    );
    let mut t = TestGame::new(2);
    let nadu = t.battlefield(P0, "Nadu, Winged Wisdom");
    let lib = set_library(&mut t, P0, &["Memnite", "Island"]);
    grow(&mut t, nadu);
    t.settle();
    assert_eq!(nadu_triggers(&t), 1);
    t.resolve_all();
    assert!(is_in(&t, lib[0], Zone::Hand(P0)));
}

#[test]
fn nadus_granted_triggers_resolve_after_nadu_leaves() {
    cr!("603.2", "113.7a");
    ruling!(
        "Nadu, Winged Wisdom",
        "If Nadu leaves the battlefield while one or more triggered abilities generated by the ability it grants are still on the stack, those abilities will still resolve as normal."
    );
    let mut t = TestGame::new(2);
    let nadu = t.battlefield(P0, "Nadu, Winged Wisdom");
    let bears = t.battlefield(P0, "Grizzly Bears");
    let lib = set_library(&mut t, P0, &["Island", "Memnite"]);
    grow(&mut t, bears);
    t.settle();
    assert_eq!(nadu_triggers(&t), 1);
    crate::r_s02_common::destroy(&mut t, nadu);
    t.resolve_all();
    // The land was put onto the battlefield.
    assert!(t.on_battlefield(lib[0]));
}

#[test]
fn nadu_entering_after_the_target_was_chosen_doesnt_trigger() {
    cr!("603.2", "603.10");
    ruling!(
        "Nadu, Winged Wisdom",
        "If Nadu somehow enters the battlefield while a spell or ability that targets a creature you control is on the stack, the ability granted by Nadu won't trigger"
    );
    let mut t = TestGame::new(2);
    let bears = t.battlefield(P0, "Grizzly Bears");
    let lib = set_library(&mut t, P0, &["Memnite", "Island"]);
    grow(&mut t, bears);
    t.settle();
    t.enter(P0, "Nadu, Winged Wisdom");
    t.settle();
    assert_eq!(nadu_triggers(&t), 0);
    t.resolve_all();
    assert_eq!(t.pt(bears), (5, 5));
    assert!(is_in(&t, lib[0], Zone::Library(P0)));
}

#[test]
fn two_nadus_grant_two_independent_abilities() {
    cr!("603.2", "113.2c");
    ruling!(
        "Nadu, Winged Wisdom",
        "If you somehow control more than one Nadu, each permanent you control will have that many instances of the granted ability. These abilities are not redundant."
    );
    // Spark Double enters as a copy of Nadu that isn't legendary.
    let mut t = TestGame::new(2);
    let nadu = t.battlefield(P0, "Nadu, Winged Wisdom");
    t.answer_choose(P0, &[obj(nadu)]);
    t.enter(P0, "Spark Double");
    t.resolve_all();
    assert_eq!(t.named_on_battlefield("Nadu, Winged Wisdom").len(), 2);
    let bears = t.battlefield(P0, "Grizzly Bears");
    for (n, want) in [(1, 2), (2, 2), (3, 0)] {
        grow(&mut t, bears);
        t.settle();
        assert_eq!(nadu_triggers(&t), want, "targeting {n}");
        t.resolve_all();
    }
}

#[test]
fn case_file_auditor_triggers_when_a_case_is_solved() {
    cr!("719.3a", "719.3b");
    supported("Case File Auditor");
    supported("Case of the Filched Falcon");
    ruling!(
        "Case File Auditor",
        "Case File Auditor's first ability triggers whenever a \"to solve\" ability you control resolves."
    );
    // Case of the Filched Falcon: "To solve — You control three or more artifacts. (If
    // unsolved, solve at the beginning of your end step.)"
    for artifacts in [2, 3] {
        let mut t = TestGame::new(2);
        t.battlefield(P0, "Case File Auditor");
        t.battlefield(P0, "Case of the Filched Falcon");
        for _ in 0..artifacts {
            t.battlefield(P0, "Ornithopter");
        }
        let lib = set_library(
            &mut t,
            P0,
            &["Island", "Swamp", "Plains", "Forest", "Wastes", "Mountain", "Memnite"],
        );
        t.advance_to(P0, Step::End);
        t.resolve_all();
        // Solved: the top six were looked at and put on the bottom. Not solved: nothing.
        let top = library_top_first(&t, P0)[0];
        assert_eq!(top == lib[6], artifacts == 3, "{artifacts} artifacts");
    }
}
