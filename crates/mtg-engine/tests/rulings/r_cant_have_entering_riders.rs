//! CR 113.11 for what a resolving ability says a permanent it puts onto the battlefield
//! has ("return that card to the battlefield ... It has flying ..."): "If a resolving
//! spell or ability creates a continuous effect that would add the specified ability to
//! such an object, that part of that continuous effect does not apply; however, other
//! parts of that continuous effect will still apply ..."

use crate::r_s01_common::supported;
use crate::r_s02_common::destroy;
use mtg_engine::keywords::KeywordKind;
use mtg_engine::testing::*;
use mtg_engine::*;

#[test]
fn valkyries_call_returns_a_creature_that_cant_have_flying_without_it_for_good() {
    cr!("113.11", "611.2e");
    ruling!(
        "Archetype of Imagination",
        "While you control an Archetype, continuous effects generated by the resolution of spells and abilities that would give the specified ability to creatures your opponents control aren't created."
    );
    supported("Valkyrie's Call");
    supported("Archetype of Imagination");
    // Valkyrie's Call: "Whenever a nontoken, non-Angel creature you control dies, return
    // that card to the battlefield under its owner's control with a +1/+1 counter on it.
    // It has flying and is an Angel in addition to its other types." P1's Archetype of
    // Imagination: "Creatures your opponents control lose flying and can't have or gain
    // flying."
    let mut t = TestGame::new(2);
    t.battlefield(P0, "Valkyrie's Call");
    let archetype = t.battlefield(P1, "Archetype of Imagination");
    let bears = t.battlefield(P0, "Grizzly Bears");
    destroy(&mut t, bears);
    t.resolve_all();
    let back = t.named_on_battlefield("Grizzly Bears");
    assert_eq!(back.len(), 1);
    let back = back[0];
    let has_flying = |t: &TestGame| t.g.obj(back).chars.has_keyword(KeywordKind::Flying);
    assert!(!has_flying(&t));
    // The rest of the effect applies: it's an Angel, with its +1/+1 counter.
    assert!(t.g.obj(back).chars.has_subtype("Angel"));
    assert_eq!(t.pt(back), (3, 3));
    // "... even if later in the turn Archetype of Courage left the battlefield": the
    // flying part never applies.
    destroy(&mut t, archetype);
    t.g.recompute();
    assert!(!t.on_battlefield(archetype));
    assert!(!has_flying(&t));
    assert!(t.g.obj(back).chars.has_subtype("Angel"));
    // Without the Archetype, the returned creature has flying.
    let mut t = TestGame::new(2);
    t.battlefield(P0, "Valkyrie's Call");
    let bears = t.battlefield(P0, "Grizzly Bears");
    destroy(&mut t, bears);
    t.resolve_all();
    let back = t.named_on_battlefield("Grizzly Bears")[0];
    assert!(t.g.obj(back).chars.has_keyword(KeywordKind::Flying));
}
