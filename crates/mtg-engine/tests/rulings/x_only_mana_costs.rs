//! Mana that may be spent only on costs that contain {X} (Rosheen Meanderer, Nexos,
//! Elementalist's Palette; CR 106.6) paying {X} costs outside a spell's or ability's own
//! announced X (item small-fixes-2): an X the text of the cost defines ("{X}, where X is
//! ...", CR 107.3c) in an attack tax (Sphere of Safety, Collective Restraint, Nils), an
//! alternative cost an effect offers (Kentaro), costs asked for as an ability or spell
//! resolves (Arcum's Whistle, Champions of Minas Tirith, Transmute Artifact), a tax set up
//! with a resolving ability's X (War Tax, War Cadence), and the {X} of special actions
//! (suspend, morph: CR 107.3d, 116.2f). Ordinary mana still pays each of them, and the
//! restricted mana still can't pay a tax without {X} (Ghostly Prison).

use crate::r_p106_common::*;
use crate::r_s01_common::attack_with;
use mtg_engine::decision::{Action, SpecialAction};
use mtg_engine::kw::offered_costs::OFFERED_ALT_COST;
use mtg_engine::mana::ManaType;
use mtg_engine::object::{CastMethod, Zone};
use mtg_engine::testing::*;
use mtg_engine::turn::Step;
use mtg_engine::types::*;
use mtg_engine::*;

const OFFERED: CastMethod = CastMethod::Alternative(OFFERED_ALT_COST);

/// How `p` pays: with Rosheen Meanderer's {C}{C}{C}{C}, which may be spent only on costs
/// that contain {X} (tapped as the cost is paid, CR 508.1i, 601.2g), or with Wastes.
#[derive(Clone, Copy, Debug, PartialEq)]
enum Pay {
    Rosheen,
    /// A Forest with Nexos's "{T}: Add {C}{C}. Spend this mana only on costs that contain
    /// {X}."
    Nexos,
    Wastes,
}

/// Puts `p`'s mana source for `pay` onto the battlefield: Rosheen Meanderer, or four
/// Wastes. Returns the permanents.
fn source(t: &mut TestGame, p: PlayerId, pay: Pay) -> Vec<ObjectId> {
    match pay {
        Pay::Rosheen => vec![t.battlefield(p, "Rosheen Meanderer")],
        Pay::Nexos => {
            t.battlefield(p, "Nexos");
            t.lands(p, "Forest", 1)
        }
        Pay::Wastes => t.lands(p, "Wastes", 4),
    }
}

/// Puts the restricted mana of `src` into `p`'s pool now (Rosheen's four, or Nexos's two
/// from the Forest); Wastes are tapped as the cost is paid.
fn x_only_mana_now(t: &mut TestGame, p: PlayerId, pay: Pay, src: &[ObjectId]) {
    match pay {
        Pay::Rosheen => t.activate(p, src[0], 0, &[]).map(|_| ()).unwrap(),
        // The Forest's second ability: the one Nexos grants.
        Pay::Nexos => t.activate(p, src[0], 1, &[]).map(|_| ()).unwrap(),
        Pay::Wastes => {}
    }
}

fn tapped(t: &TestGame, ids: &[ObjectId]) -> usize {
    ids.iter().filter(|o| t.obj_now(**o).tapped).count()
}

/// P0 attacks P1 with Grizzly Bears (another creature than the mana source) in P0's turn;
/// whether it's attacking.
fn bears_attack(t: &mut TestGame, bears: ObjectId) -> bool {
    attack_with(t, &[(bears, Entity::Player(P1))]);
    t.g.attackers().contains(&bears)
}

#[test]
fn x_only_mana_pays_an_attack_tax_whose_x_the_text_defines() {
    cr!("106.6", "107.3c", "508.1h");
    interp!("defined-x-cost-contains-x");
    ruling!(
        "Rosheen Meanderer",
        "If it’s something you can spend mana on, it’s a cost. If that cost includes the {X} symbol in it, you can spend mana generated by Rosheen on that cost."
    );
    ruling!(
        "Nils, Discipline Enforcer",
        "All counters on a creature are considered when determining the value of X, not only +1/+1 counters."
    );
    ruling!(
        "Collective Restraint",
        "Domain abilities count the number of basic land types among lands you control, not how many lands you control or how many of any type."
    );
    for tax in [
        "Sphere of Safety",
        "Collective Restraint",
        "Nils, Discipline Enforcer",
    ] {
        for pay in [Pay::Rosheen, Pay::Nexos, Pay::Wastes] {
            let mut t = TestGame::new(2);
            t.battlefield(P1, tax);
            let bears = t.battlefield(P0, "Grizzly Bears");
            // X = 2 each time.
            let x = match tax {
                // "the number of enchantments you control": Sphere and another one.
                "Sphere of Safety" => {
                    t.battlefield(P1, "Glorious Anthem");
                    2
                }
                // Two basic land types among three lands.
                "Collective Restraint" => {
                    t.lands(P1, "Plains", 2);
                    t.lands(P1, "Island", 1);
                    2
                }
                // "the number of counters on that creature": all its counters.
                _ => {
                    t.g.add_counters(Entity::Object(bears), "+1/+1", 1, None);
                    t.g.add_counters(Entity::Object(bears), "stun", 1, None);
                    2
                }
            };
            let src = source(&mut t, P0, pay);
            t.set_step(P0, Step::PrecombatMain);
            assert!(
                bears_attack(&mut t, bears),
                "{tax} {pay:?}\n{}",
                t.dump_log()
            );
            match pay {
                // Rosheen tapped for four, two of them spent.
                Pay::Rosheen => {
                    assert_eq!(tapped(&t, &src), 1, "{tax}");
                    assert_eq!(pool_total(&t, P0), 4 - x, "{tax}");
                }
                // The Forest tapped for its {C}{C}, both spent.
                Pay::Nexos => {
                    assert_eq!(tapped(&t, &src), 1, "{tax}");
                    assert_eq!(pool_total(&t, P0), 0, "{tax}");
                }
                Pay::Wastes => assert_eq!(tapped(&t, &src), x as usize, "{tax}"),
            }
        }
    }
}

