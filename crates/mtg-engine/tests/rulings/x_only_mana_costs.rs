    t.set_step(P0, Step::PrecombatMain);
    assert!(bears_attack(&mut t, bears), "{}", t.dump_log());
    assert_eq!(tapped(&t, &rosheen), 1);
    assert_eq!(pool_total(&t, P0), 0);
