    // Sphere of Safety (X = 2: it and Ghostly Prison are P1's enchantments) and Ghostly
    // Prison ({2}): the total cost to attack, {4}, contains {X}, so Rosheen's four mana
    // pay all of it.
    let mut t = TestGame::new(2);
    t.battlefield(P1, "Sphere of Safety");
    t.battlefield(P1, "Ghostly Prison");
    let bears = t.battlefield(P0, "Grizzly Bears");
