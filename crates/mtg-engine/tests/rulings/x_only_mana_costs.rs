#[test]
fn x_only_mana_pays_war_taxs_and_war_cadences_x() {
    cr!("106.6", "107.3", "508.1h", "509.1d", "608.2h");
    interp!("defined-x-cost-contains-x");
    ruling!(
        "Rosheen Meanderer",
        "If it’s something you can spend mana on, it’s a cost. If that cost includes the {X} symbol in it, you can spend mana generated by Rosheen on that cost."
    );
    // War Tax with X = 2: "This turn, creatures can't attack unless their controller pays
    // {X} for each attacking creature they control."
    for pay in [Pay::Rosheen, Pay::Wastes] {
        let mut t = TestGame::new(2);
        let war_tax = t.battlefield(P1, "War Tax");
        let bears = t.battlefield(P0, "Grizzly Bears");
        let src = source(&mut t, P0, pay);
        t.set_step(P0, Step::PrecombatMain);
        mana(&mut t, P1, ManaType::U, 1);
        mana(&mut t, P1, ManaType::C, 2);
        t.answer(P1, DecisionKind::X, Answer::Number(2));
        t.g.turn.priority = Some(P1);
        t.activate(P1, war_tax, 0, &[]).unwrap();
        t.resolve_all();
        assert!(bears_attack(&mut t, bears), "{pay:?}\n{}", t.dump_log());
        match pay {
            Pay::Nexos => unreachable!("not paid with Nexos here"),
            Pay::Rosheen => assert_eq!(pool_total(&t, P0), 2),
            Pay::Wastes => assert_eq!(tapped(&t, &src), 2),
        }
    }
    // War Cadence with X = 1: "This turn, creatures can't block unless their controller
    // pays {X} for each blocking creature they control." P1 blocks, paying {1}.
    for pay in [Pay::Rosheen, Pay::Wastes] {
        let mut t = TestGame::new(2);
        let cadence = t.battlefield(P0, "War Cadence");
        let bears = t.battlefield(P0, "Grizzly Bears");
        let wall = t.battlefield(P1, "Wall of Wood");
        let src = source(&mut t, P1, pay);
        t.set_step(P0, Step::PrecombatMain);
        mana(&mut t, P0, ManaType::R, 1);
        mana(&mut t, P0, ManaType::C, 1);
        t.answer(P0, DecisionKind::X, Answer::Number(1));
        t.activate(P0, cadence, 0, &[]).unwrap();
        t.resolve_all();
        attack_with(&mut t, &[(bears, Entity::Player(P1))]);
        crate::r_p148_common::declare_blocks(&mut t, P1, &[(wall, bears)]);
        assert!(
            t.g.combat.as_ref().unwrap().is_blocked(bears),
            "{pay:?}\n{}",
            t.dump_log()
        );
        match pay {
            Pay::Nexos => unreachable!("not paid with Nexos here"),
            Pay::Rosheen => assert_eq!(pool_total(&t, P1), 3),
            Pay::Wastes => assert_eq!(tapped(&t, &src), 1),
        }
    }
}

#[test]
fn x_only_mana_pays_kentaros_alternative_cost() {
    cr!("106.6", "107.3c", "118.9", "601.2f");
    interp!("defined-x-cost-contains-x");
    ruling!(
        "Kentaro, the Smiling Cat",
        "Kentaro doesn’t change when you can cast Samurai. It just makes Samurai castable for generic mana."
    );
    ruling!(
        "Rosheen Meanderer",
        "A spell’s total cost includes either its mana cost (printed in the upper right corner) or its alternative cost (such as flashback), as well as any additional costs (such as kicker)."
    );
    // Samurai of the Pale Curtain ({W}{W}) for {X}, X = 2: with Rosheen's mana or with
    // colorless mana.
    for pay in [Pay::Rosheen, Pay::Wastes] {
        let mut t = TestGame::new(2);
        t.battlefield(P0, "Kentaro, the Smiling Cat");
        t.set_step(P0, Step::PrecombatMain);
        match pay {
            Pay::Nexos => unreachable!("not paid with Nexos here"),
            Pay::Rosheen => {
                let r = t.battlefield(P0, "Rosheen Meanderer");
                t.activate(P0, r, 0, &[]).unwrap();
            }
            Pay::Wastes => mana(&mut t, P0, ManaType::C, 4),
        }
        let samurai = t.hand(P0, "Samurai of the Pale Curtain");
        t.cast(P0, samurai).method(OFFERED).go();
        assert_eq!(pool_total(&t, P0), 2, "{pay:?}");
        t.resolve_all();
        assert_eq!(
            t.named_on_battlefield("Samurai of the Pale Curtain").len(),
            1,
            "{pay:?}"
        );
    }
    // Without Kentaro, Rosheen's mana can't cast it: its mana cost has no {X}.
    let mut t = TestGame::new(2);
    t.set_step(P0, Step::PrecombatMain);
    let r = t.battlefield(P0, "Rosheen Meanderer");
    t.activate(P0, r, 0, &[]).unwrap();
    mana(&mut t, P0, ManaType::W, 1);
    let samurai = t.hand(P0, "Samurai of the Pale Curtain");
    assert!(t.cast(P0, samurai).try_go().is_err());
}

