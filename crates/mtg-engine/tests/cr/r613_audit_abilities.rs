#[test]
fn losing_all_abilities_removes_earlier_grants_but_not_later_ones() {
    cr!("613.1f", "613.7", "613.7b", "613.9");
    ruling!(
        "Turn to Frog",
        "If the affected creature gains an ability after Turn to Frog resolves, it will keep that ability"
    );
    // Jump, then Turn to Frog: no flying.
    let mut t = TestGame::new(2);
    let bears = t.battlefield(P0, "Grizzly Bears");
    cast_resolve(&mut t, P0, "Jump", &[Entity::Object(bears)]);
    cast_resolve(&mut t, P1, "Turn to Frog", &[Entity::Object(bears)]);
    t.g.recompute();
    assert!(!has_kw(&t, bears, KeywordKind::Flying));
    assert_eq!(ability_count(&t, bears), 0);
    // Turn to Frog, then Jump: flying.
    let mut t = TestGame::new(2);
    let bears = t.battlefield(P0, "Grizzly Bears");
    cast_resolve(&mut t, P1, "Turn to Frog", &[Entity::Object(bears)]);
    cast_resolve(&mut t, P0, "Jump", &[Entity::Object(bears)]);
    t.g.recompute();
    assert!(has_kw(&t, bears, KeywordKind::Flying));
    assert_eq!(ability_count(&t, bears), 1);
    assert_eq!(t.pt(bears), (1, 1));
    assert!(has_subtype(&t, bears, "Frog"));
}

#[test]
fn cant_have_flying_beats_later_grants_and_keyword_counters() {
    // CR 113.11: an object that can't have an ability loses it and can't be given it by
    // a resolving effect (that part of the effect isn't created) or a keyword counter;
    // static abilities' effects resume when the "can't have" effect ends.
    cr!("113.11", "613.1f", "613.7c", "613.7");
    ruling!(
        "Archetype of Imagination",
        "continuous effects generated by static abilities (such as an Aura that granted the appropriate ability) would resume applying if the Archetype left the battlefield"
    );
    ruling!(
        "Archetype of Imagination",
        "a spell cast by an opponent that gives creatures they control first strike wouldn't cause the creatures to have first strike, even if later in the turn Archetype of Courage left the battlefield"
    );
    let mut t = TestGame::new(2);
    let archetype = t.battlefield(P0, "Archetype of Imagination");
    let drake = t.battlefield(P1, "Wind Drake");
    let bears = t.battlefield(P1, "Grizzly Bears");
    let elves = t.battlefield(P1, "Llanowar Elves");
    t.g.recompute();
    assert!(!has_kw(&t, drake, KeywordKind::Flying));
    cast_resolve(&mut t, P1, "Jump", &[Entity::Object(bears)]);
    put_counters(&mut t, elves, "flying", 1);
    let flight = t.battlefield(P1, "Flight");
    assert!(t.g.attach(flight, Entity::Object(drake)));
    t.g.recompute();
    for c in [drake, bears, elves] {
        assert!(!has_kw(&t, c, KeywordKind::Flying));
    }
    // The Archetype leaves: the Aura and the counter work again; Jump's effect was
    // never created.
    t.g.destroy(archetype, None);
    t.settle();
    t.g.recompute();
    assert!(has_kw(&t, drake, KeywordKind::Flying));
    assert!(has_kw(&t, elves, KeywordKind::Flying));
    assert!(!has_kw(&t, bears, KeywordKind::Flying));
}

#[test]
fn archetype_of_imagination_follows_control_changes() {
    // Layer 2 before layer 6: "creatures you control" and "creatures your opponents
    // control" are evaluated after control-changing effects.
    cr!("613.1b", "613.1f", "613.1", "611.3a");
    ruling!(
        "Archetype of Imagination",
        "The Archetype's second ability applies to each creature controlled by any of your opponents, no matter when it entered the battlefield"
    );
    let mut t = TestGame::new(2);
    let archetype = t.battlefield(P0, "Archetype of Imagination");
    let bears = t.battlefield(P0, "Grizzly Bears");
    let drake = t.battlefield(P1, "Wind Drake");
    t.g.recompute();
    assert!(has_kw(&t, bears, KeywordKind::Flying));
    assert!(!has_kw(&t, drake, KeywordKind::Flying));
    cast_resolve(&mut t, P0, "Control Magic", &[Entity::Object(drake)]);
    t.g.recompute();
    assert_eq!(controller(&t, drake), P0);
    assert!(has_kw(&t, drake, KeywordKind::Flying), "P0's creature now");
    // P1 takes the Archetype: its controller's creatures have flying, P0's can't.
    t.set_step(P1, mtg_engine::turn::Step::PrecombatMain);
    cast_resolve(&mut t, P1, "Control Magic", &[Entity::Object(archetype)]);
    t.g.recompute();
    assert_eq!(controller(&t, archetype), P1);
    assert!(!has_kw(&t, bears, KeywordKind::Flying));
    assert!(!has_kw(&t, drake, KeywordKind::Flying), "still P0's, and P0 is P1's opponent");
    assert!(has_kw(&t, archetype, KeywordKind::Flying));
}

#[test]
fn an_added_artifact_type_and_a_type_setting_aura_apply_in_timestamp_order() {
    cr!("613.1d", "613.7", "613.7b", "613.7e", "205.1a");
    ruling!(
        "Kenrith's Transformation",
        "loses any other card types it has (such as artifact)"
    );
    ruling!("Liquimetal Coating", "Becoming an artifact doesn't change what color(s) a permanent is");
    // Liquimetal Coating first, then the Aura: not an artifact.
    let mut t = TestGame::new(2);
    let bears = t.battlefield(P0, "Grizzly Bears");
    let coating = t.battlefield(P0, "Liquimetal Coating");
    activate_containing(&mut t, P0, coating, "artifact", &[Entity::Object(bears)]);
    t.g.recompute();
    assert!(is_type(&t, bears, CardType::Artifact));
    assert_eq!(colors(&t, bears), color_set(&[Color::Green]));
    let elk = t.battlefield(P1, "Kenrith's Transformation");
    assert!(t.g.attach(elk, Entity::Object(bears)));
    t.g.recompute();
    assert!(!is_type(&t, bears, CardType::Artifact));
    assert!(has_subtype(&t, bears, "Elk") && !has_subtype(&t, bears, "Bear"));
    assert_eq!(t.pt(bears), (3, 3));
    // The Aura first, then Liquimetal Coating: an artifact Elk creature.
    let mut t = TestGame::new(2);
    let bears = t.battlefield(P0, "Grizzly Bears");
    let elk = t.battlefield(P1, "Kenrith's Transformation");
    assert!(t.g.attach(elk, Entity::Object(bears)));
    let coating = t.battlefield(P0, "Liquimetal Coating");
    activate_containing(&mut t, P0, coating, "artifact", &[Entity::Object(bears)]);
    t.g.recompute();
    assert!(is_type(&t, bears, CardType::Artifact));
    assert!(is_type(&t, bears, CardType::Creature));
    assert!(has_subtype(&t, bears, "Elk"));
    assert_eq!(colors(&t, bears), color_set(&[Color::Green]));
    end_turn(&mut t);
    assert!(!is_type(&t, bears, CardType::Artifact));
    assert!(has_subtype(&t, bears, "Elk"));
}

#[test]
fn titanias_song_keeps_applying_to_the_artifacts_it_animated_in_layer_4() {
    // CR 613.6: the set of noncreature artifacts is determined in layer 4; the ability
    // removal (6) and the power/toughness setting (7b) apply to the same permanents even
    // though they're creatures by then. An artifact creature isn't affected at all.
    cr!("613.6", "613.1d", "613.1f", "613.4b", "611.3a", "704.5f");
    let mut t = TestGame::new(2);
    let stone = t.battlefield(P0, "Mind Stone");
    let thopter = t.battlefield(P0, "Ornithopter");
    let citadel = t.battlefield(P0, "Darksteel Citadel");
    t.battlefield(P1, "Titania's Song");
    t.settle();
    t.g.recompute();
    assert!(t.obj_now(stone).is_creature());
    assert_eq!(t.pt(stone), (2, 2));
    assert_eq!(ability_count(&t, stone), 0);
    assert!(is_type(&t, stone, CardType::Artifact));
    // Ornithopter was already a creature: untouched.
    assert!(has_kw(&t, thopter, KeywordKind::Flying));
    assert_eq!(t.pt(thopter), (0, 2));
    // Darksteel Citadel: a 0/0 artifact land creature that lost indestructible; it's put
    // into the graveyard for having toughness 0 anyway.
    assert!(!t.on_battlefield(citadel));
    // A noncreature artifact entering later is affected too (CR 611.3a).
    let stone2 = t.battlefield(P0, "Mind Stone");
    t.g.recompute();
    assert!(t.obj_now(stone2).is_creature());
    assert_eq!(t.pt(stone2), (2, 2));
}

#[test]
fn painters_servant_feeds_crusade_and_protection_until_a_later_color_change() {
    // Layer 5 (the chosen color added) determines what Crusade (7c) applies to and what
    // protection from white stops (CR 613.9); a later "colorless" overrides the Servant
    // in layer 5, and a Servant later than the Lattice adds its color to colorless things.
    cr!("613.9", "613.1e", "613.4c", "613.7", "702.16b", "704.5m");
    ruling!("Painter's Servant", "This ability doesn't overwrite any previous colors");
    ruling!(
        "Painter's Servant",
        "If something affected by Painter's Servant is normally colorless, it will simply be the new color"
    );
    let mut t = TestGame::new(2);
    t.battlefield(P0, "Crusade");
    let knight = t.battlefield(P0, "Black Knight");
    let bears = t.battlefield(P1, "Grizzly Bears");
    let rancor = t.battlefield(P0, "Rancor");
    assert!(t.g.attach(rancor, Entity::Object(knight)));
    let stone = t.battlefield(P1, "Mind Stone");
    t.g.recompute();
    assert_eq!(t.pt(knight), (4, 2), "Rancor's +2/+0; Crusade doesn't apply");
    assert_eq!(t.pt(bears), (2, 2));
    assert!(!t.g.protected_from(knight, bears));
    let blade = t.hand(P1, "Doom Blade");
    t.lands(P1, "Swamp", 2);
    choose_color(&mut t, P1, Color::White);
    t.enter(P1, "Painter's Servant");
    t.resolve_all();
    t.g.recompute();
    assert_eq!(colors(&t, knight), color_set(&[Color::Black, Color::White]));
    assert_eq!(colors(&t, stone), color_set(&[Color::White]), "colorless becomes just white");
    assert_eq!(t.pt(bears), (3, 3), "white now: Crusade applies");
    assert!(t.g.protected_from(knight, bears), "protection from white against a white creature");
    assert!(t.g.protected_from(knight, blade), "and against a white Doom Blade");
    // Rancor became white: an illegal Aura on a creature with protection from white
    // (CR 704.5m); its own trigger then returns it to its owner's hand.
    assert!(!t.on_battlefield(rancor));
    assert!(t.in_hand(P0, "Rancor"));
    assert_eq!(t.pt(knight), (3, 3), "Crusade's +1/+1, no Rancor");
    // Mycosynth Lattice (later): everything is colorless, Crusade stops.
    let lattice = t.battlefield(P1, "Mycosynth Lattice");
    t.g.recompute();
    assert_eq!(colors(&t, bears), ColorSet::NONE);
    assert_eq!(t.pt(bears), (2, 2));
    assert!(!t.g.protected_from(knight, bears));
    // Doom Blade can't target a black creature: the Bears is black and white now.
    choose_color(&mut t, P0, Color::Black);
    t.enter(P0, "Painter's Servant");
    t.resolve_all();
    t.g.recompute();
    assert_eq!(colors(&t, bears), color_set(&[Color::Black]));
    t.g.turn.priority = Some(P1);
    assert!(t.cast(P1, blade).target(bears).try_go().is_err(), "no nonblack creature to target");
    assert!(t.in_hand(P1, "Doom Blade"));
    // A second Servant (later than the Lattice) makes everything white again.
    choose_color(&mut t, P0, Color::White);
    t.enter(P0, "Painter's Servant");
    t.resolve_all();
    t.g.recompute();
    assert_eq!(colors(&t, bears), color_set(&[Color::Black, Color::White]));
    assert_eq!(colors(&t, lattice), color_set(&[Color::Black, Color::White]));
    assert_eq!(t.pt(bears), (3, 3));
}

#[test]
fn kwende_waits_for_the_effect_giving_first_strike_whatever_the_timestamps() {
    // "Creatures you control with first strike have double strike" depends on an Aura's
    // "enchanted creature has first strike" (CR 613.8a: it changes what Kwende's effect
    // applies to), so it applies after it even though Kwende is older (CR 613.8b).
    cr!("613.8", "613.8a", "613.8b", "613.1f", "702.4b");
    let mut t = TestGame::new(2);
    let kwende = t.battlefield(P0, "Kwende, Pride of Femeref");
    let bears = t.battlefield(P0, "Grizzly Bears");
    let lance = t.battlefield(P0, "Lance");
    assert!(t.g.attach(lance, Entity::Object(bears)));
    t.g.recompute();
    assert!(has_kw(&t, bears, KeywordKind::FirstStrike));
    assert!(has_kw(&t, bears, KeywordKind::DoubleStrike));
    assert!(has_kw(&t, kwende, KeywordKind::DoubleStrike));
    // Turn to Frog on the Bears (later than both): it loses first strike, so Kwende's
    // effect no longer applies to it.
    cast_resolve(&mut t, P1, "Turn to Frog", &[Entity::Object(bears)]);
    t.g.recompute();
    assert!(!has_kw(&t, bears, KeywordKind::FirstStrike));
    assert!(!has_kw(&t, bears, KeywordKind::DoubleStrike));
    // Humility removes Kwende's ability (dependency): nothing has double strike, even
    // though the Lance would still give first strike without Humility.
    end_turn(&mut t);
    assert!(has_kw(&t, bears, KeywordKind::DoubleStrike));
    t.battlefield(P1, "Humility");
    t.g.recompute();
    assert!(!has_kw(&t, bears, KeywordKind::FirstStrike), "the Lance is older than Humility");
    assert!(!has_kw(&t, bears, KeywordKind::DoubleStrike));
    assert!(!has_kw(&t, kwende, KeywordKind::DoubleStrike));
}

#[test]
fn humility_and_akromas_memorial_apply_in_timestamp_order() {
    cr!("613.1f", "613.7", "613.7a", "613.7d");
    // Memorial first: Humility removes everything it grants.
    let mut t = TestGame::new(2);
    let bears = t.battlefield(P0, "Grizzly Bears");
    t.battlefield(P0, "Akroma's Memorial");
    t.g.recompute();
    assert!(has_kw(&t, bears, KeywordKind::Flying));
    assert!(has_kw(&t, bears, KeywordKind::Protection));
    t.battlefield(P1, "Humility");
    t.g.recompute();
    assert_eq!(ability_count(&t, bears), 0);
    // Humility first: the Memorial's grants are later and apply.
    let mut t = TestGame::new(2);
    let bears = t.battlefield(P0, "Grizzly Bears");
    t.battlefield(P1, "Humility");
    t.battlefield(P0, "Akroma's Memorial");
    t.g.recompute();
    assert!(has_kw(&t, bears, KeywordKind::Flying));
    assert!(has_kw(&t, bears, KeywordKind::FirstStrike));
    assert!(has_kw(&t, bears, KeywordKind::Vigilance));
    assert!(has_kw(&t, bears, KeywordKind::Trample));
    assert!(has_kw(&t, bears, KeywordKind::Haste));
    assert!(has_kw(&t, bears, KeywordKind::Protection));
    assert_eq!(t.pt(bears), (1, 1));
}

#[test]
fn an_aura_made_a_creature_by_march_of_the_machines_is_put_into_the_graveyard() {
    // Layer 4 (Lattice makes the Aura an artifact, March makes the noncreature artifact a
    // creature) feeds the state-based action for an Aura attached illegally (CR 704.5m).
    cr!("613.1d", "613.8a", "704.5m", "303.4f");
    ruling!(
        "Mycosynth Lattice",
        "An Aura that’s also a creature can’t enchant anything"
    );
    let mut t = TestGame::new(2);
    let bears = t.battlefield(P0, "Grizzly Bears");
    let rancor = t.battlefield(P0, "Rancor");
    assert!(t.g.attach(rancor, Entity::Object(bears)));
    t.battlefield(P1, "March of the Machines");
    t.g.recompute();
    assert!(t.on_battlefield(rancor), "an Aura isn't an artifact yet");
    assert_eq!(t.pt(bears), (4, 2));
    t.battlefield(P1, "Mycosynth Lattice");
    t.resolve_all();
    t.g.recompute();
    assert!(!t.on_battlefield(rancor));
    assert!(t.in_hand(P0, "Rancor"), "its own trigger returned it from the graveyard");
    assert_eq!(t.pt(bears), (2, 2));
}

#[test]
fn rule_modifying_effects_see_the_final_characteristics() {
    // CR 613.11: "as long as this creature's power is 5 or greater, it can attack as
    // though it didn't have defender" is checked after every layer, so counters and
    // pumps (layer 7c) and a setting effect (7b) count.
    cr!("613.11", "613.4c", "613.4b", "702.3b");
    let mut t = TestGame::new(2);
    let karsus = t.battlefield(P0, "Karsus Depthguard");
    t.set_step(P0, mtg_engine::turn::Step::DeclareAttackers);
    t.g.recompute();
    assert_eq!(t.pt(karsus), (4, 3));
    assert!(!t.g.can_attack(karsus));
    put_counters(&mut t, karsus, counters::PLUS1, 1);
    assert_eq!(t.pt(karsus), (5, 4));
    assert!(t.g.can_attack(karsus));
    cast_resolve(&mut t, P1, "Ovinize", &[Entity::Object(karsus)]);
    t.g.recompute();
    assert_eq!(t.pt(karsus), (1, 2));
    assert!(!has_kw(&t, karsus, KeywordKind::Defender), "it lost defender too");
    assert!(t.g.can_attack(karsus));
}

#[test]
fn maximum_hand_size_effects_apply_in_timestamp_order() {
    cr!("613.11", "613.10", "613.7", "613.7a");
    let mut t = TestGame::new(2);
    assert_eq!(t.g.player(P0).max_hand_size, Some(7));
    let profusion = t.battlefield(P0, "Null Profusion");
    t.g.recompute();
    assert_eq!(t.g.player(P0).max_hand_size, Some(2));
    let vessel = t.battlefield(P0, "Thought Vessel");
    t.g.recompute();
    assert_eq!(t.g.player(P0).max_hand_size, None, "the later effect wins");
    t.g.destroy(profusion, None);
    t.battlefield(P0, "Null Profusion");
    t.g.recompute();
    assert_eq!(t.g.player(P0).max_hand_size, Some(2));
    t.g.destroy(vessel, None);
    t.settle();
    t.g.recompute();
    assert_eq!(t.g.player(P0).max_hand_size, Some(2));
    assert_eq!(t.g.player(P1).max_hand_size, Some(7));
}
