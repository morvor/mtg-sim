/// Reports that a player performed a keyword action (for "whenever you [action]"
/// triggers, `TriggerCond::PlayerAction`).
pub fn emit(g: &mut Game, name: &str, player: PlayerId, obj: Option<ObjectId>, amount: i32) {
    g.emit(Event::Custom {
        name: SmolStr::new(name),
        player: Some(player),
        obj,
        amount,
    });
}

/// Whether `id` is (still) a permanent on the battlefield.
pub fn on_battlefield(g: &Game, id: ObjectId) -> bool {
    g.is_live(id) && g.obj(id).zone == Zone::Battlefield
}

/// The player who controls `id`, or, if it's no longer on the battlefield, who last
/// controlled it (its last known information, e.g. CR 701.44c, 701.50b).
pub fn controller_or_last(g: &Game, id: ObjectId) -> PlayerId {
    g.obj(id).controller
}

/// Picks which of `remaining` performs an action next when several objects are
/// instructed to perform it at the same time: the first player in APNAP order who
/// controls (or last controlled) one or more of them chooses one (CR 701.44d, 701.50c).
/// Removes and returns it.
pub fn next_in_apnap_order(
    g: &mut Game,
    remaining: &mut Vec<ObjectId>,
    source: Option<ObjectId>,
    prompt: &str,
) -> Option<ObjectId> {
    if remaining.is_empty() {
        return None;
    }
    let order = g.apnap();
    let chooser = order
        .iter()
        .copied()
        .find(|p| remaining.iter().any(|o| controller_or_last(g, *o) == *p))
        .unwrap_or_else(|| controller_or_last(g, remaining[0]));
    let mine: Vec<ObjectId> = remaining
        .iter()
        .copied()
        .filter(|o| controller_or_last(g, *o) == chooser)
        .collect();
    let pick = if mine.len() == 1 {
        mine[0]
    } else {
        g.ask_objects(chooser, source, prompt, mine.clone(), 1, 1)
            .first()
            .copied()
            .unwrap_or(mine[0])
    };
    remaining.retain(|o| *o != pick);
    Some(pick)
}

/// The number of an instruction (at least 0).
pub fn number(g: &Game, n: &Value, ctx: &Ctx) -> u32 {
    g.eval_value(n, ctx).max(0) as u32
}
