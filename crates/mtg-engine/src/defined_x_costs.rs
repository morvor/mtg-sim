//! "{X}, where X is [value]" in a cost that isn't the cost of the spell or ability whose
//! text defines X ([`CostPart::DefinedX`]): an attack tax ("Creatures can't attack you
//! unless their controller pays {X} for each of those creatures, where X is the number of
//! enchantments you control", Sphere of Safety; Nils, Discipline Enforcer; Collective
//! Restraint), an alternative cost an effect offers ("You may pay {X} rather than pay the
//! mana cost for Samurai spells you cast, where X is that spell's mana value", Kentaro, the
//! Smiling Cat), and the {X} of an attack tax a resolving ability set up with its own X
//! ("This turn, creatures can't attack unless their controller pays {X} for each attacking
//! creature they control", War Tax, X fixed as the effect begins, CR 608.2h).
//!
//! X is defined by the text, so no player chooses it (CR 107.3c); its value is determined
//! with the rest of the total cost (CR 508.1h, 509.1d, 601.2f) and is then X generic mana.
//! The cost still contains {X}: mana that may be spent only on costs that contain {X}
//! (Rosheen Meanderer, Elementalist's Palette, Nexos; CR 106.6) may pay any part of it
//! (their rulings: "You can spend mana generated by Rosheen on any part of a cost that
//! contains {X}").
//!
//! - [`lock`] (with the other amounts of the total cost, `cumulative_upkeep::
//!   expand_repeated`) evaluates X, keeping the part;
//! - [`fold`] then turns the parts into generic mana where the mana is paid or checked, and
//!   says whether there were any, so that the payment's spending context knows the cost
//!   contains {X}.

use crate::ability::*;
use crate::eval::Ctx;
use crate::game::Game;
use crate::mana::{ManaCost, ManaSymbol};

/// Whether the cost has an {X} the text defines (in any of its parts).
pub fn has_defined_x(cost: &Cost) -> bool {
    cost.parts.iter().any(part_has_defined_x)
}

fn part_has_defined_x(part: &CostPart) -> bool {
    match part {
        CostPart::DefinedX(_) => true,
        CostPart::Repeated { cost, .. } => has_defined_x(cost),
        CostPart::OneOf(v) => v.iter().any(has_defined_x),
        CostPart::AnyNumberOf { part, .. } | CostPart::AndPayItsManaCost(part) => {
            part_has_defined_x(part)
        }
        _ => false,
    }
}

/// Whether the cost contains {X}, either announced (its mana has {X}) or defined by the
/// text ([`CostPart::DefinedX`]).
pub fn contains_x(cost: &Cost) -> bool {
    cost.mana.as_ref().is_some_and(|m| m.has_x()) || has_defined_x(cost)
}

/// The value of X of a defined {X} part, determined now (CR 508.1h, 601.2f): the part
/// keeps it from then on.
pub fn lock(g: &Game, part: &CostPart, ctx: &Ctx) -> Option<CostPart> {
    match part {
        CostPart::DefinedX(v) if v.as_const().is_none() => {
            // CR 107.1b: a negative amount of mana is 0.
            Some(CostPart::DefinedX(Value::c(
                g.eval_value(v, ctx).max(0) as i32
            )))
        }
        _ => None,
    }
}

/// The cost with each defined {X} part (top-level) replaced by that much generic mana, and
/// whether there was any (then the cost contains {X}, CR 106.6). A cost of {X} with X = 0 is
/// still a cost: {0} (CR 118.5).
pub fn fold(g: &Game, cost: &Cost, ctx: &Ctx) -> (Cost, bool) {
    if !cost
        .parts
        .iter()
        .any(|p| matches!(p, CostPart::DefinedX(_)))
    {
        return (cost.clone(), false);
    }
    let mut generic = 0u32;
    let mut parts = Vec::new();
    for part in &cost.parts {
        match part {
            CostPart::DefinedX(v) => generic += g.eval_value(v, ctx).max(0) as u32,
            other => parts.push(other.clone()),
        }
    }
    let mut mana = cost.mana.clone().unwrap_or_default();
    mana.add(&ManaCost::generic(generic));
    if mana.symbols.is_empty() {
        mana.symbols.push(ManaSymbol::Generic(0));
    }
    (
        Cost {
            mana: Some(mana),
            parts,
        },
        true,
    )
}
